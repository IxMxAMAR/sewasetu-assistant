#!/usr/bin/env bash
#
# First boot on the pilot host.
#
# The host is a Runpod CPU pod. It runs this as its start command, which means
# the box takes its own deployment rather than being pushed to:
#
#   1. clone this repository at the branch it is told to follow,
#   2. fetch the department's data snapshot from the department's own handout,
#   3. write pilot.env for this host, including the public addresses Runpod
#      gives it, which are the token audiences the two MCP servers check,
#   4. run deploy/provision.sh,
#   5. hand PID 1 to supervisor, which keeps the four services alive.
#
# Because this runs on every boot, a restarted pod comes back by itself. It is
# also why pilot.env is generated rather than committed: it holds the officer's
# password, and it is different on every host.
#
# The Runpod start command is:
#
#   bash -c "apt-get update -qq && apt-get install -y -qq git curl ca-certificates \
#            && curl -sSL https://raw.githubusercontent.com/IxMxAMAR/sewasetu-assistant/main/deploy/bootstrap.sh | bash"
#
set -euo pipefail

REPO_URL="${REPO_URL:-https://github.com/IxMxAMAR/sewasetu-assistant.git}"
REPO_REF="${REPO_REF:-main}"
APP_DIR="${APP_DIR:-/opt/sewasetu/app}"
# Everything that has to outlive a process lives here: pilot.env, the database,
# the uploaded age proofs and the two Python environments. Point this at a pod
# volume if the host has one.
STATE_DIR="${STATE_DIR:-/opt/sewasetu/state}"

# The department published this link with the handout. The 100k-row snapshot is
# the department's data, not ours, so it is fetched from them rather than
# carried in our repository.
HANDOUT_ZIP_URL="${HANDOUT_ZIP_URL:-https://drive.google.com/uc?export=download&id=1vpY9JvXL5iFesJ2vkMhC-b4tL89PAL50}"

log() { printf '\n=== %s\n' "$*"; }

# There is nobody at the console on the pilot host, so a failure here has to be
# loud in the pod log and then get out of the way: the container exits, Runpod
# starts it again, and the whole thing is retried from the top.
trap 'code=$?; echo "bootstrap: failed (exit $code) at line $LINENO; retrying in 60s" >&2; sleep 60; exit $code' ERR

log "repository"
if [ -d "$APP_DIR/.git" ]; then
    git -C "$APP_DIR" fetch --depth 1 origin "$REPO_REF"
    git -C "$APP_DIR" reset --hard FETCH_HEAD
else
    mkdir -p "$(dirname "$APP_DIR")"
    git clone --depth 1 --branch "$REPO_REF" "$REPO_URL" "$APP_DIR"
fi
git -C "$APP_DIR" --no-pager log -1 --format='deployed commit %h  %s'

log "the department's data snapshot"
if [ ! -s "$APP_DIR/seed/seed.sql" ]; then
    command -v unzip >/dev/null || { apt-get update -qq && apt-get install -y -qq unzip; }
    echo "downloading the handout"
    curl -fsSL "$HANDOUT_ZIP_URL" -o /tmp/handout.zip
    unzip -o -j /tmp/handout.zip '*/seed/seed.sql' -d "$APP_DIR/seed/" >/dev/null 2>&1 \
        || unzip -o -j /tmp/handout.zip 'seed/seed.sql' -d "$APP_DIR/seed/" >/dev/null
    rm -f /tmp/handout.zip
fi
[ -s "$APP_DIR/seed/seed.sql" ] || { echo "bootstrap: could not obtain seed/seed.sql" >&2; exit 1; }
echo "seed.sql present ($(du -h "$APP_DIR/seed/seed.sql" | cut -f1))"

log "this host's public addresses"
# Runpod gives every pod an id and proxies the ports it was created with. The
# portal stamps these into its sign-in tokens, and each MCP server checks that a
# token's audience is its own address, so they have to be derived from the pod
# rather than guessed.
POD_ID="${POD_ID:-${RUNPOD_POD_ID:-}}"
if [ -z "$POD_ID" ]; then
    echo "bootstrap: neither POD_ID nor RUNPOD_POD_ID is set; cannot work out the public URLs" >&2
    exit 1
fi

mkdir -p "$STATE_DIR"
cat > "$STATE_DIR/pilot.env" <<ENV
# Generated by deploy/bootstrap.sh on $(date -u '+%Y-%m-%d %H:%M UTC'). Not committed.
PUBLIC_BASE_URL=https://${POD_ID}-8000.proxy.runpod.net
CITIZEN_MCP_URL=https://${POD_ID}-8101.proxy.runpod.net
OFFICER_MCP_URL=https://${POD_ID}-8102.proxy.runpod.net

ADMIN_USERNAME=${ADMIN_USERNAME:-admin}
ADMIN_PASSWORD=${ADMIN_PASSWORD:-$(head -c 18 /dev/urandom | base64 | tr -d '/+=' | cut -c1-16)}
SECRET_KEY=${SECRET_KEY:-$(head -c 32 /dev/urandom | od -An -tx1 | tr -d ' \n')}

AGENT_PILOT_BLOCKS=${AGENT_PILOT_BLOCKS:-Sonari,Namti}

# The evals drive a small model as the assistant and another as the citizen.
# They only run on a boot that asks for them.
OPENROUTER_API_KEY=${OPENROUTER_API_KEY:-}
EVAL_MODEL=${EVAL_MODEL:-google/gemini-3.1-flash-lite}
EVAL_LLM_BASE=${EVAL_LLM_BASE:-}
RUN_EVALS=${RUN_EVALS:-0}
ENV
chmod 600 "$STATE_DIR/pilot.env"
grep -E 'PUBLIC_BASE_URL|CITIZEN_MCP_URL|OFFICER_MCP_URL|ADMIN_USERNAME|AGENT_PILOT_BLOCKS' \
    "$STATE_DIR/pilot.env"
echo "ADMIN_PASSWORD: see $STATE_DIR/pilot.env"

log "provisioning"
START_SUPERVISORD=0 bash "$APP_DIR/deploy/provision.sh"

log "supervisor in the foreground"
exec supervisord -n -c /etc/supervisor/supervisord.conf
